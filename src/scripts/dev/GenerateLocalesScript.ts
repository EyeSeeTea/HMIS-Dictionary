import fs from "fs";
import path from "path";
import { po } from "gettext-parser";

const i18nDir = "i18n";
const localesDir = path.join("src", "locales");
const namespace = "hmis-dictionary";

/* Write src/locales from i18n/*.po and i18n/en.pot: one translations.json per language, and an
   index.js that adds them all to i18n.

   This replaces @dhis2/d2-i18n-generate (run as `-l`, library mode), which brought in argparse 1
   and, through it, sprintf-js (GHSA-hp3w-g68c-fv3c, no fixed release; see SECURITY.md). Same
   output: the texts of each file in its order, without the obsolete (#~) entries, so an empty
   translation stays empty and i18n falls back to the English text.
*/
function main() {
    const files = fs
        .readdirSync(i18nDir)
        .filter(fileName => [".po", ".pot"].includes(path.extname(fileName)))
        .sort();
    const languages = files.map(fileName => path.basename(fileName, path.extname(fileName)));

    fs.rmSync(localesDir, { recursive: true, force: true });

    files.forEach((fileName, index) => {
        const language = languages[index] ?? "";
        const translations = getTranslations(fs.readFileSync(path.join(i18nDir, fileName)));
        const dir = path.join(localesDir, language);

        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(
            path.join(dir, "translations.json"),
            JSON.stringify(translations, null, 4)
        );
        console.info(`Written: ${Object.keys(translations).length} texts for ${language}`);
    });

    fs.writeFileSync(path.join(localesDir, "index.js"), getIndex(languages));
}

function getTranslations(content: Buffer): Record<string, string> {
    const entries = Object.values(po.parse(content).translations[""] ?? {});

    return Object.fromEntries(
        entries.filter(entry => entry.msgid).map(entry => [entry.msgid, entry.msgstr[0] ?? ""])
    );
}

function getIndex(languages: string[]): string {
    const imports = languages.map(
        language => `import ${language}Translations from './${language}/translations.json';`
    );
    const resources = languages.map(
        language => `i18n.addResources('${language}', namespace, ${language}Translations);`
    );

    return [
        "// Generated by src/scripts/dev/GenerateLocalesScript.ts (`yarn localize`). Do not edit.",
        "import i18n from '@dhis2/d2-i18n';",
        "",
        ...imports,
        "",
        `const namespace = '${namespace}';`,
        "",
        ...resources,
        "",
        "export default i18n;",
        "",
    ].join("\n");
}

main();
